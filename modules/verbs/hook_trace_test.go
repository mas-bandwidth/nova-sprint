// The walk tla/HookTrace.tla checks against tla/Hook.tla (tla/make-traces.sh,
// group hook): the verbs on store.Fake and the fake bus, each step one of
// the model's (the bus hook started or stopped, a hook, an unhook, an acting
// verb), with the code's answer and the state after it.

var hookNames = []string{"alice", "bob", "carol"}

// hookStep is one record of the trace: the step, whether the code accepted
// it, and after it the bus's live session id for each name (0 off the bus),
// the id and role its row records (0 and none when not hooked), and whether
// its row holds live cards.
type hookStep struct {
	action, name, arg string
	ok                bool
	live, rec         map[string]int
	role              map[string]string
	hand              map[string]bool
}

// hookWalk is the fixtures' sprint with nobody hooked or on the bus: alice
// and bob each hold a working card. The bus gives a name's hook the ids b1,
// b2, ... as it is started.
type hookWalk struct {
	t      *testing.T
	w      *world
	starts map[string]int
	steps  []hookStep
}

func newHookWalk(t *testing.T) *hookWalk {
	t.Helper()
	s := sprint()
	for n, r := range s.Rows {
		r.Session, r.Role = "", ""
		s.Rows[n] = r
	}
	h := &hookWalk{t: t, w: worldFrom(t, s), starts: map[string]int{}}
	h.w.bus.present, h.w.bus.session = map[string]bool{}, map[string]string{}
	h.record("Init", "-", "-", true)
	return h
}

func (h *hookWalk) record(action, name, arg string, ok bool) {
	h.t.Helper()
	st := hookStep{action: action, name: name, arg: arg, ok: ok, live: map[string]int{}, rec: map[string]int{}, role: map[string]string{}, hand: map[string]bool{}}
	snap := h.w.snap(h.t)
	for _, n := range hookNames {
		if h.w.bus.present[n] {
			st.live[n] = h.starts[n]
		}
		row := snap.Rows[n]
		if row.Session != "" {
			id, err := strconv.Atoi(strings.TrimPrefix(row.Session, "b"))
			if err != nil {
				h.t.Fatalf("row %s records session %q, not one the bus gave", n, row.Session)
			}
			st.rec[n] = id
		}
		st.role[n] = cmp.Or(row.Role, "none")
	}
	for _, c := range snap.Cards {
		if live(c) {
			st.hand[c.Holder] = true
		}
	}
	h.steps = append(h.steps, st)
}

func (h *hookWalk) busStart(n string) {
	h.starts[n]++
	h.w.bus.present[n], h.w.bus.session[n] = true, "b"+strconv.Itoa(h.starts[n])
	h.record("BusStart", n, "-", true)
}

func (h *hookWalk) busStop(n string) {
	h.w.bus.present[n] = false
	h.record("BusStop", n, "-", true)
}

// run is one command as n: accepted (exit 0) or refused (exit 1); any other
// exit is the test's failure.
func (h *hookWalk) run(action, n, arg string, args ...string) bool {
	h.t.Helper()
	r := h.w.do(n, args...)
	if r.Exit != 0 && r.Exit != 1 {
		h.t.Fatalf("%s %s %s: exit %d:\n%s", action, n, arg, r.Exit, r.Output)
	}
	h.record(action, n, arg, r.Exit == 0)
	return r.Exit == 0
}

func (h *hookWalk) hook(n, role string) bool {
	return h.run("Hook", n, role, "hook", "--role", role)
}
func (h *hookWalk) unhook(n string) bool { return h.run("Unhook", n, "-", "unhook") }

// verb is an acting verb that writes nothing: a worker's (queue) or the
// coordinator's (a dry-run hold).
func (h *hookWalk) verb(n, need string) bool {
	if need == "coordinator" {
		return h.run("Verb", n, need, "hold", "dave", "--reason", "r", "--dry-run")
	}
	return h.run("Verb", n, need, "queue")
}

func (h *hookWalk) tla() string {
	fn := func(f func(n string) string) string {
		parts := make([]string, len(hookNames))
		for i, n := range hookNames {
			parts[i] = n + " |-> " + f(n)
		}
		return "[" + strings.Join(parts, ", ") + "]"
	}
	var b strings.Builder
	b.WriteString("---------------------------- MODULE HookTraceLog ----------------------------\n")
	b.WriteString("\\* Generated by modules/verbs/hook_trace_test.go; do not edit.\n")
	b.WriteString("EXTENDS Naturals, Sequences\nTraceLog == <<\n")
	for i, s := range h.steps {
		comma := ","
		if i == len(h.steps)-1 {
			comma = ""
		}
		fmt.Fprintf(&b, "  [i |-> %d, action |-> %q, name |-> %q, arg |-> %q, ok |-> %s, live |-> %s, rec |-> %s, role |-> %s, hand |-> %s]%s\n",
			i+1, s.action, s.name, s.arg, strings.ToUpper(strconv.FormatBool(s.ok)),
			fn(func(n string) string { return strconv.Itoa(s.live[n]) }), fn(func(n string) string { return strconv.Itoa(s.rec[n]) }),
			fn(func(n string) string { return strconv.Quote(s.role[n]) }), fn(func(n string) string { return strings.ToUpper(strconv.FormatBool(s.hand[n])) }), comma)
	}
	b.WriteString(">>\n=============================================================================\n")
	return b.String()
}

// write puts the trace under NOVA_TRACE_DIR/<name>, when that is set; with
// cfg "" the trace is checked with tla/HookTrace.cfg.
func (h *hookWalk) write(name, cfg string) {
	h.t.Helper()
	dir := os.Getenv("NOVA_TRACE_DIR")
	if dir == "" {
		return
	}
	sub := filepath.Join(dir, name)
	if err := os.MkdirAll(sub, 0o755); err != nil {
		h.t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(sub, "HookTraceLog.tla"), []byte(h.tla()), 0o644); err != nil {
		h.t.Fatal(err)
	}
	if cfg == "" {
		return
	}
	if err := os.WriteFile(filepath.Join(sub, "HookTrace.cfg"), []byte(cfg), 0o644); err != nil {
		h.t.Fatal(err)
	}
}

// hookWalkSteps is each walk's length; with at most one bus start a step it
// stays within tla/HookTrace.cfg's MaxStarts (64).
const hookWalkSteps = 60

// TestHookTraceWalk walks the hook's steps at random and writes each walk's
// trace for TLC (per commit, -short, a quarter of the seeds). Together the
// seeds walk what the model checks the code on: a verb refused on a new bus
// session, a stale hook replaced with a hand held, a verb accepted after it,
// and the hand returned by an unhook.
func TestHookTraceWalk(t *testing.T) {
	t.Parallel()
	seeds := 16
	if testing.Short() {
		seeds = 4
	}
	seen := map[string]bool{}
	for seed := 1; seed <= seeds; seed++ {
		h := newHookWalk(t)
		rng := rand.New(rand.NewPCG(uint64(seed), 2026))
		for range hookWalkSteps {
			n := hookNames[rng.IntN(len(hookNames))]
			role := []string{"worker", "coordinator"}[rng.IntN(2)]
			before := h.steps[len(h.steps)-1]
			stale := before.live[n] != 0 && before.rec[n] != 0 && before.rec[n] != before.live[n]
			switch k := rng.IntN(12); {
			case k < 2:
				h.busStart(n)
			case k < 3:
				if before.live[n] != 0 {
					h.busStop(n)
				}
			case k < 6:
				if ok := h.hook(n, role); ok && stale && before.hand[n] {
					seen["a stale hook replaced with a hand held"] = true
					if after := h.steps[len(h.steps)-1]; !after.hand[n] {
						t.Fatalf("seed %d: the hook that replaced %s's stale one returned its hand", seed, n)
					}
				}
			case k < 7:
				if ok := h.unhook(n); ok && before.hand[n] && before.rec[n] != 0 {
					seen["a hand returned by an unhook"] = true
				}
			default:
				ok := h.verb(n, role)
				if ok && before.rec[n] != before.live[n] {
					t.Fatalf("seed %d: a verb as %s was accepted with recorded bus session %d and live %d", seed, n, before.rec[n], before.live[n])
				}
				seen["a verb refused on a new bus session"] = seen["a verb refused on a new bus session"] || !ok && stale
				seen["a verb accepted on a later bus session"] = seen["a verb accepted on a later bus session"] || ok && before.live[n] > 1
			}
		}
		h.write(fmt.Sprintf("hook-walk-%d", seed), "")
	}
	for _, s := range []string{"a verb refused on a new bus session", "a stale hook replaced with a hand held", "a verb accepted on a later bus session", "a hand returned by an unhook"} {
		if !seen[s] {
			t.Fatalf("no walk had %s", s)
		}
	}
}

// hookTraceCfg is tla/HookTrace.cfg after its expect line.
const hookTraceCfg = `CONSTANTS
  Names = {"alice", "bob", "carol"}
  MaxStarts = 64

SPECIFICATION TraceSpec
CHECK_DEADLOCK FALSE

INVARIANTS
  TypeOK
  NoStaleVerb
  HookWellFormed
  OneCoordinator
  HandKept

PROPERTY TraceMatched
`

// TestHookTraceRefusesDivergence holds the breaker: the incident's steps on
// the code (carol hooks in as coordinator, her session ends, a new one
// starts the bus hook only, and her coordinator verb is refused), then the
// same trace with that last answer as it was before the fix: accepted. The
// model must refuse the forged record; the trace is the fixture
// tla/traces/hook-breaker, checked by tla/make-traces.sh.
func TestHookTraceRefusesDivergence(t *testing.T) {
	t.Parallel()
	h := newHookWalk(t)
	h.busStart("carol")
	if !h.hook("carol", "coordinator") || !h.verb("carol", "coordinator") {
		t.Fatal("carol did not hook in and act")
	}
	h.busStop("carol")
	h.busStart("carol")
	if h.verb("carol", "coordinator") {
		t.Fatal("a coordinator verb was accepted on a new bus session")
	}
	h.steps[len(h.steps)-1].ok = true // the gate before the fix
	cfg := fmt.Sprintf("\\* Generated by modules/verbs/hook_trace_test.go; do not edit.\n\\* expect: forbidden at %d\n", len(h.steps)) + hookTraceCfg
	h.write("hook-breaker", cfg)
	for name, got := range map[string]string{"HookTraceLog.tla": h.tla(), "HookTrace.cfg": cfg} {
		want, err := os.ReadFile(filepath.Join("..", "..", "tla", "traces", "hook-breaker", name))
		if err != nil || string(want) != got {
			t.Fatalf("tla/traces/hook-breaker/%s is stale (%v): run this test with NOVA_TRACE_DIR=tla/traces and commit it", name, err)
		}
	}
	if own, err := os.ReadFile(filepath.Join("..", "..", "tla", "HookTrace.cfg")); err != nil || string(own) != "\\* expect: matched\n"+hookTraceCfg {
		t.Fatalf("tla/HookTrace.cfg is not the cfg the breaker is written with (%v)", err)
	}
}
