#!/usr/bin/env python3
"""Generate the policy model's reversed witnesses and every cfg from Policy.tla.

Run from anywhere: python3 tla/make-policy-witnesses.py. The same shape as
make-witnesses.py (the store's) and make-card-witnesses.py: each witness is
Policy.tla with its module renamed, a header naming the fault, and exact
text replacements; a replacement that does not match exactly the expected
number of times stops the script, so a change to Policy.tla that a fault no
longer fits fails here instead of producing a witness that tests nothing.
Commit the generated files; CI runs them as they are.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# Every invariant of the passing run, in cfg order.
INVARIANTS = [
    "TypeOK", "ActiveStored", "AnsweredByUsable", "TickAlwaysAnswered", "ActivateMovesNoCard",
    "OneJudgementPerVersion", "WaitKeepsItsBound", "FallbackWasActive", "NoAnswerStartsNothing",
]

CONSTANTS = "CONSTANT MaxVersion = 3\nSPECIFICATION Spec\n"

# Reachability checks: each must be violated on Policy.tla.
REACH = {
    "NeverPrevAnswers": "a tick is answered by the previous active version",
    "NeverDefaultAnswers": "a tick is answered by the built-in",
    "NeverJudged": "a policy judgement opens",
    "NeverNoAnswer": "a tick where the built-in fails too",
    "NeverRollback": "an older version is activated again",
    "NeverWaitAcrossActivate": "an activation while the card is working",
}

# (name, target, fault, replacements): the design's six reversed witnesses
# and one for WaitKeepsItsBound.
WITNESSES = [
    ("PolicyActivateUnstored", "ActiveStored",
     "Activate has no stored check: a version never set is activated.",
     [("Activate(v) ==\n  /\\ v \\in stored\n", "Activate(v) ==\n  /\\ TRUE   \\* FAULT: was v \\in stored\n", 1)]),
    ("PolicyTickStalls", "TickAlwaysAnswered",
     "Pick has no last resort: when every version breaks, the built-in\nincluded, the tick is answered by nothing (the stall).",
     [("  ELSE NoAnswer\n", "  ELSE None   \\* FAULT: was NoAnswer\n", 1)]),
    ("PolicyDefaultSkipped", "TickAlwaysAnswered",
     "Pick never tries the built-in: a tick goes without an answer while\nthe built-in would have answered it.",
     [("  ELSE IF Default \\notin breaks THEN Default\n", "  ELSE IF FALSE THEN Default   \\* FAULT: was Default \\notin breaks\n", 1)]),
    ("PolicyBrokenDefaultUsed", "AnsweredByUsable",
     "Pick takes the built-in on trust: a failing built-in answers the tick.",
     [("  ELSE IF Default \\notin breaks THEN Default\n", "  ELSE IF TRUE THEN Default   \\* FAULT: was Default \\notin breaks\n", 1)]),
    ("PolicyNoAnswerDeals", "NoAnswerStartsNothing",
     "A tick with no answer deals anyway: the card starts work.",
     [("       /\\ (c = \"working\" /\\ card = \"ready\") => Pick # NoAnswer   \\* a deal needs an answer\n", "       /\\ TRUE   \\* FAULT: was a deal needs an answer\n", 1)]),
    ("PolicyActivateMovesCard", "ActivateMovesNoCard",
     "Activate re-deals the card: a policy change moves it.",
     [("  /\\ card' = card   \\* a policy change never moves a card\n", "  /\\ card' = Advance(card)   \\* FAULT: was card\n", 1)]),
    ("PolicyBreakingUsed", "AnsweredByUsable",
     "Pick ignores breaks for the active version: a failing version\nanswers the tick.",
     [("  IF active \\notin breaks THEN active\n", "  IF TRUE THEN active   \\* FAULT: was active \\notin breaks\n", 1)]),
    ("PolicyFallbackNeverActive", "FallbackWasActive",
     "Set records the new version as the previous one: a fallback goes\nto a version that was never active.",
     [("  /\\ stored' = stored \\cup {v}\n  /\\ prev' = prev\n", "  /\\ stored' = stored \\cup {v}\n  /\\ prev' = v   \\* FAULT: was prev\n", 1)]),
    ("PolicyJudgementEveryTick", "OneJudgementPerVersion",
     "Tick opens a judgement for a failing version every tick, not only\nwhen none is open.",
     [("IF u \\in Failing /\\ judgements[u] = 0 THEN 1 ELSE", "IF u \\in Failing THEN judgements[u] + 1 ELSE", 1)]),
    ("PolicyWaitRebound", "WaitKeepsItsBound",
     "Activate re-bounds a wait in progress by the new version's timeouts.",
     [("  /\\ waitBound' = waitBound\n", "  /\\ waitBound' = IF card = \"working\" THEN v ELSE waitBound   \\* FAULT\n", 1)]),
]


def die(msg):
    sys.stderr.write("make-policy-witnesses: " + msg + "\n")
    sys.exit(1)


def header(name, fault, target):
    title = " MODULE " + name + " "
    left = (77 - len(title)) // 2
    line = "-" * left + title + "-" * (77 - len(title) - left)
    lines = ["REVERSED WITNESS. FAULT:"] + fault.split("\n")
    lines += ["TLC must report " + target + " violated. Everything else is",
              "Policy.tla unchanged (generated by make-policy-witnesses.py)."]
    for l in lines:
        if len(l) > 71:
            die(name + ": header line over 71 characters: " + l)
    box = ["(" + "*" * 75 + ")"]
    box += ["(* " + l.ljust(71) + " *)" for l in lines]
    box += ["(" + "*" * 75 + ")"]
    return line, "\n".join(box)


def cfg(target):
    out = ["\\* Reversed witness: TLC must report " + target + " violated.",
           "\\* The target invariant is listed first so it is the one TLC names."]
    text = "\n".join(out) + "\n" + CONSTANTS
    return text + "".join("INVARIANT " + i + "\n" for i in [target] + [i for i in INVARIANTS if i != target])


def main():
    with open(os.path.join(HERE, "Policy.tla")) as f:
        base = f.read()
    first = base.split("\n", 1)
    if "MODULE Policy " not in first[0]:
        die("Policy.tla does not start with its module line")
    for i in INVARIANTS + list(REACH):
        if "\n" + i + " ==" not in base:
            die(i + " is not defined in Policy.tla")
    for name, target, fault, reps in WITNESSES:
        if target not in INVARIANTS:
            die(name + ": unknown target " + target)
        text = first[1]
        for old, new, count in reps:
            n = text.count(old)
            if n != count:
                die("%s: expected %d match(es), found %d, for:\n%s" % (name, count, n, old))
            text = text.replace(old, new)
        line, box = header(name, fault, target)
        with open(os.path.join(HERE, "witnesses", name + ".tla"), "w") as f:
            f.write(line + "\n" + box + "\n" + text)
        with open(os.path.join(HERE, "witnesses", name + ".cfg"), "w") as f:
            f.write(cfg(target))
    with open(os.path.join(HERE, "Policy.cfg"), "w") as f:
        f.write(CONSTANTS + "".join("INVARIANT " + i + "\n" for i in INVARIANTS))
    for name, what in REACH.items():
        with open(os.path.join(HERE, "reach", "Policy" + name + ".cfg"), "w") as f:
            f.write("\\* Reachability on Policy: TLC must report %s violated (%s).\n" % (name, what)
                    + CONSTANTS + "INVARIANT %s\n" % name)


main()
