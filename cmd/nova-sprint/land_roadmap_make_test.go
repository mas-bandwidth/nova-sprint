// TestTheLanderRegeneratesTheRoadmapThroughTheReposOwnMakeRoadmap is the card
// the-lander-regenerates-the-roadmap-through-the-repos-own-make-roadmap: the lander runs a
// repository's own `make roadmap` for the FIXES.md and ROADMAP.md families, whatever the
// repository's tools/roadmap holds. In a repository like mas-bandwidth/schema, tools/roadmap
// is not a main package and `go run ./tools/roadmap` can never work; a fake repository here
// holds tools/roadmap/doc.go as `package roadmap` and a Makefile whose roadmap target writes
// the page, so the two families must go through make.
func TestTheLanderRegeneratesTheRoadmapThroughTheReposOwnMakeRoadmap(t *testing.T) {
	t.Parallel()
	if _, err := exec.LookPath("make"); err != nil {
		t.Skip("make is on no PATH entry: " + err.Error())
	}
	const line = "regenerated by the repository own make roadmap\n"
	for _, tc := range []struct {
		name  string
		owned string
	}{
		{"the roadmap's page", "ROADMAP.md"},
		{"the points release's page", "FIXES.md"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			dir := t.TempDir()
			require.NoError(t, os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/fake\n\ngo 1.24\n"), 0o644))
			require.NoError(t, os.MkdirAll(filepath.Join(dir, "tools", "roadmap"), 0o755))
			// as mas-bandwidth/schema's is: a non-main package, so `go run ./tools/roadmap` cannot run
			require.NoError(t, os.WriteFile(filepath.Join(dir, "tools", "roadmap", "doc.go"), []byte("package roadmap\n"), 0o644))
			makefile := "roadmap:\n\tprintf '%s\\n' 'regenerated by the repository own make roadmap' > " + tc.owned + "\n"
			require.NoError(t, os.WriteFile(filepath.Join(dir, "Makefile"), []byte(makefile), 0o644))

			i := slices.IndexFunc(landLedgers, func(l landLedger) bool { return l.owns(tc.owned) })
			require.GreaterOrEqual(t, i, 0, "a family owns "+tc.owned)
			family := landLedgers[i]

			out, err := (&lander{}).regen(context.Background(), dir, family.run)
			require.NoError(t, err, out)
			got, err := os.ReadFile(filepath.Join(dir, tc.owned))
			require.NoError(t, err)
			assert.Equal(t, line, string(got))
		})
	}
}
